%%  Задание 8. Факториал N! без функции factorial
%% ------------------------------------------------------------------------
N = 10;
fprintf('\n=== Задание 8 ===\n');

% Вариант 1: цикл for
f1 = 1;
for k = 1:N
    f1 = f1 * k;
